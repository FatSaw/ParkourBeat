package ru.sortix.parkourbeat.levels;

import lombok.Getter;
import lombok.NonNull;
import org.bukkit.Material;

/**
 * ПОЛНОЕ НЕБО ИЛИ ПОЛОВИНА.
 * <p>
 * Выбирается один раз при создании уровня и решает ровно одно: НА КАКОЙ ВЫСОТЕ
 * появится площадка со спавном.
 * <p>
 * КАК ЭТО РАБОТАЕТ НА САМОМ ДЕЛЕ. Тёмную нижнюю половину неба рисует клиент, и решает
 * он это сам, по двум вещам: считает ли он мир плоским и на какой высоте камера.
 * В обычном (не плоском) мире горизонт стоит на 63, и всё, что ниже, клиент закрывает
 * тёмной плоскостью пустоты - это и есть «половина неба». Поднимитесь выше 63 - и небо
 * станет полным само собой, безо всяких настроек.
 * <p>
 * Плоским мир считается по тому, что записано в {@code level.dat}. Шаблонные уровни
 * (3D, 2D, дуэльные) копируются вместе с этим файлом и приезжают плоскими - у них небо
 * полное на любой высоте. А «Копатель» и 360 создаются пустым миром, без шаблона и без
 * чужого {@code level.dat}, - и они плоскими НЕ считаются. Именно поэтому высота
 * работала у «Копателя» и не работала больше нигде.
 * <p>
 * ПОЭТОМУ ВЫБОР ДЕРЖИТСЯ ДВУМЯ СПОСОБАМИ СРАЗУ.
 * <ol>
 *     <li>ВЫСОТА ПЛОЩАДКИ - как и было. Работает у тех, чей мир создаётся пустым.</li>
 *     <li>ФЛАГ ПЛОСКОСТИ, который уезжает клиенту в пакете входа в мир. Его правит
 *         {@link ru.sortix.parkourbeat.player.SkyFlatnessManager}, и работает он у всех
 *         режимов и на любой высоте - в том числе у шаблонных, чей {@code level.dat}
 *         никто не трогает.</li>
 * </ol>
 * Два способа не спорят друг с другом: оба говорят клиенту одно и то же, просто разными
 * словами. Второй нужен потому, что первый физически не может помочь уровню, который
 * приехал из шаблона плоским.
 */
@Getter
public enum SkyMode {

    /**
     * Полное небо. Площадка ставится выше горизонта, и тёмной половины не видно.
     * <p>
     * Именно так «Копатель» и создавался всегда - просто это не было ничьим выбором,
     * а числом внутри его собственных настроек.
     */
    FULL(Material.WHITE_CONCRETE, "&fПолное небо", 120),

    /**
     * Половина неба. Площадка ставится низко, под горизонтом, и клиент рисует тёмный
     * низ - тот самый вид, который до сих пор получался у 360-уровней случайно.
     */
    HALF(Material.QUARTZ_SLAB, "&7Половина неба", 15);

    /**
     * Высота площадки при полном небе.
     * <p>
     * Сильно выше горизонта, а не впритык: на 64 небо уже полное, но любая яма в декоре
     * глубиной в блок возвращает игрока под горизонт, и низ снова темнеет. Сто двадцать
     * оставляют запас и вниз, и вверх - под потолочный декор и ламповые стены.
     */
    public static final int HIGH_Y_VALUE = FULL.platformY;

    /**
     * Высота площадки при половине неба.
     * <p>
     * Пятнадцать, а не ноль: под площадкой должно остаться место на провалы, шахты и
     * нижние ярусы, а над ней - полсотни блоков до горизонта, за которые небо не успеет
     * стать полным.
     */
    public static final int LOW_Y_VALUE = HALF.platformY;

    private final @NonNull Material icon;
    private final @NonNull String displayName;

    /** На какой высоте ставится площадка со спавном. */
    private final int platformY;

    SkyMode(@NonNull Material icon, @NonNull String displayName, int platformY) {
        this.icon = icon;
        this.displayName = displayName;
        this.platformY = platformY;
    }

    public boolean isFull() {
        return this == FULL;
    }

    @NonNull
    public SkyMode toggle() {
        return this == FULL ? HALF : FULL;
    }

    /**
     * Есть ли у режима выбор неба вообще.
     * <p>
     * У всех, кроме 2D. В двумерном уровне камера стоит сбоку и смотрит на плоскость,
     * а не на горизонт: половина неба там не оформление, а просто тёмная полоса
     * непонятно откуда.
     */
    public static boolean isAvailableFor(@NonNull ru.sortix.parkourbeat.twod.LevelMode mode) {
        return !mode.isTwoD();
    }

    /**
     * Прочитать значение из файла уровня.
     *
     * @return null, если ключа нет или он испорчен - у такого уровня выбора не было
     */
    @javax.annotation.Nullable
    public static SkyMode byName(@javax.annotation.Nullable String name) {
        if (name == null) return null;
        String normalized = name.trim().toUpperCase(java.util.Locale.ROOT);
        if (normalized.isEmpty()) return null;
        for (SkyMode mode : values()) {
            if (mode.name().equals(normalized)) return mode;
        }
        return null;
    }
}
