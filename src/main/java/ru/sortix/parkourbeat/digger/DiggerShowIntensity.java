package ru.sortix.parkourbeat.digger;

import lombok.Getter;
import lombok.NonNull;
import org.bukkit.Material;

/**
 * НАСЫЩЕННОСТЬ СВЕТОВОГО ШОУ.
 * <p>
 * Ступеней намеренно три. Две - это выбор между «есть» и «нет», а не настройка; пять -
 * это уже вопрос «а чем четвёртая отличается от пятой», на который нет честного ответа.
 * Три ступени человек удерживает в голове целиком и выбирает не глядя.
 * <p>
 * Все числа здесь - это ПРОМЕЖУТКИ, а не количества. Задавать «сколько эффектов на
 * трек» бессмысленно: на полутораминутном и на семиминутном треках одно и то же число
 * даст совершенно разную плотность. Промежуток же одинаково работает на любой длине.
 */
@Getter
public enum DiggerShowIntensity {

    /**
     * ЛАЙТОВО. Оформление отмечает только смену частей песни и больше ничего.
     * <p>
     * Небо меняется на границах разделов, чудо раз в восемь тактов, вспышки только на
     * самом плотном месте. Это фон, который не отвлекает от нот - для карт, где вся
     * сложность в самой раскладке.
     */
    LIGHT("Лайтово", Material.GLASS,
        0, 8, 16, 28, false),

    /**
     * СРЕДНЕ. Небо начинает работать внутри частей, а не только между ними.
     * <p>
     * На громких разделах смена приходится на каждую четырёхтактовую фразу - то есть на
     * ту же сетку, по которой построена сама музыка.
     */
    MEDIUM("Средне", Material.SEA_LANTERN,
        2, 4, 8, 56, false),

    /**
     * НАСЫЩЕННЕЕ. Оформление идёт по четырёхтактовой фразе и не замолкает почти нигде.
     * <p>
     * Небо меняется КАЖДЫЙ такт, чудо - через такт, вспышки есть даже
     * на спокойных разделах, кирка меняется вдвое чаще. На плотной карте это сплошная
     * стена света, и она для тех, кто именно этого и хочет.
     * <p>
     * Единственное, что не разгоняется, - биом-зоны: они запекаются в блоки, и цена у
     * них не в кадрах, а в секундах работы сервера.
     */
    DENSE("Насыщеннее", Material.BEACON,
        1, 2, 3, 98, true);

    private final @NonNull String display;
    private final @NonNull Material icon;

    /**
     * Через сколько ДОЛЕЙ менять небо внутри раздела. 0 - только на границах разделов.
     * <p>
     * В долях, а не в тактах, и это не придирка. Такт - это четыре доли, то есть почти
     * две секунды на среднем темпе; смена раз в такт ощущается как «иногда меняется».
     * Половина такта - две доли - уже читается как пульс в темпе песни, потому что
     * совпадает с тем, на что человек кивает головой.
     */
    private final int skyEveryBeats;

    /**
     * Минимум между чудоэффектами, В ТАКТАХ.
     * <p>
     * В тактах, а не в миллисекундах, и это принципиально: промежуток в секундах на
     * медленном треке даёт одно, на быстром другое, и в обоих случаях эффект приходится
     * в случайное место такта. Промежуток в тактах одинаково ложится на любой темп и
     * всегда попадает в долю.
     */
    private final int wonderGapBars;

    /** Минимум между сменами кирки, в тактах. */
    private final int pickaxeGapBars;

    /** Потолок числа биом-зон. */
    private final int maxBiomeZones;

    /** Ставить ли вспышки и на спокойных разделах тоже. */
    private final boolean flashEverywhere;

    DiggerShowIntensity(@NonNull String display,
                        @NonNull Material icon,
                        int skyEveryBeats,
                        int wonderGapBars,
                        int pickaxeGapBars,
                        int maxBiomeZones,
                        boolean flashEverywhere
    ) {
        this.display = display;
        this.icon = icon;
        this.skyEveryBeats = skyEveryBeats;
        this.wonderGapBars = wonderGapBars;
        this.pickaxeGapBars = pickaxeGapBars;
        this.maxBiomeZones = maxBiomeZones;
        this.flashEverywhere = flashEverywhere;
    }

    /** Короткая подсказка для меню. */
    @NonNull
    public String getHint() {
        switch (this) {
            case LIGHT:
                return "Как было раньше: по частям песни";
            case MEDIUM:
                return "Небо через полтакта, биомов 56";
            default:
                return "Рисунок на каждый такт, биомов 98";
        }
    }
}
